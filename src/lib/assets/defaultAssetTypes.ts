export function buildInstitutionAssetTypes(
  institutionId: string,
  timestamp: string,
): AssetTypeDefinition[] {
  return DEFAULT_ASSET_TYPE_TEMPLATES.map((template, index) => ({
    ...template,
    id: buildDeterministicTypeId(institutionId, index + 1),
    institutionId,
    allowedGeomTypes: [...template.allowedGeomTypes],
    fieldSchema: template.fieldSchema.map((f) => ({
      ...f,
      options: f.options ? [...f.options] : undefined,
    })),
    isActive: true,
    createdAt: timestamp,
    updatedAt: timestamp,
  }));
}

function buildDeterministicTypeId(institutionId: string, index: number): string {
  const instSuffix = institutionId.slice(-2).padStart(2, '0');
  const seq = String(index).padStart(4, '0');
  return `88888888-8888-4888-8888-0000${instSuffix}00${seq}`;
}

export function generateSuggestedAssetCode(
  prefix: string,
  campusCode: string,
): string {
  const cleanCampus = campusCode.replace(/[^A-Z0-9]/g, '').slice(0, 6) || 'CMP';
  const suffix = String(Math.floor(100 + Math.random() * 900));
  return `${prefix}-${cleanCampus}-${suffix}`;
}
